import { zodResolver } from "@hookform/resolvers/zod";
import { Check, X } from "lucide-react";
import { useState } from "react";
import { useForm } from "react-hook-form";
import { useTranslation } from "react-i18next";

import { Alert } from "@/components/common/Alert";
import { Button } from "@/components/ui/button";
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from "@/components/ui/form";
import { Input } from "@/components/ui/input";
import { parseApiError } from "@/utils/apiError";

import { useEnableTwoFactor } from "../hooks/useAccount";
import { makeEnable2faSchema, type Enable2faValues } from "../schemas/account";
import type { Setup2faResponse } from "../services/account.service";
import { RecoveryCodesPanel } from "./RecoveryCodesPanel";

// Enroll wizard: scan QR / enter manual key → confirm a TOTP code → show recovery
// codes once. Self-contained; calls onComplete after the user acks the codes.
export function TwoFactorEnroll({
  setup,
  onComplete,
  onCancel,
  onNotPending,
}: {
  setup: Setup2faResponse;
  onComplete: () => void;
  onCancel: () => void;
  onNotPending: () => void;
}) {
  const { t } = useTranslation();
  const form = useForm<Enable2faValues>({
    resolver: zodResolver(makeEnable2faSchema(t)),
    defaultValues: { code: "" },
    mode: "onChange",
  });
  const enable = useEnableTwoFactor();
  const [codes, setCodes] = useState<string[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  const onSubmit = form.handleSubmit((v) => {
    setError(null);
    enable.mutate(v.code.trim(), {
      onSuccess: (res) => setCodes(res.recovery_codes),
      onError: (err) => {
        const parsed = parseApiError(err, t);
        // Pending secret gone (e.g. cross-tab) → restart enrollment.
        if (parsed.key === "two_factor_not_pending") {
          onNotPending();
          return;
        }
        form.reset({ code: "" });
        setError(parsed.message);
      },
    });
  });

  // Step 2 — recovery codes (shown once).
  if (codes) {
    return <RecoveryCodesPanel codes={codes} onDone={onComplete} />;
  }

  // Step 1 — QR + manual key + code confirmation.
  return (
    <div className="space-y-4">
      <div className="flex flex-col items-center gap-3">
        {/* qr_svg is generated by our own backend — trusted SVG markup. */}
        <div
          className="rounded-md border p-3"
          role="img"
          aria-label={t("account.2fa.qr_alt")}
          dangerouslySetInnerHTML={{ __html: setup.qr_svg }}
        />
        <p className="max-w-sm text-center text-sm text-muted-foreground">
          {t("account.2fa.scan_hint")}
        </p>
        <div className="flex items-center gap-2">
          <span className="text-xs text-muted-foreground">
            {t("account.2fa.manual_key_label")}:
          </span>
          <code className="rounded bg-muted px-2 py-1 font-mono text-sm">
            {setup.manual_key}
          </code>
        </div>
      </div>

      {error && <Alert variant="danger" message={error} />}

      <Form {...form}>
        <form onSubmit={onSubmit} noValidate className="space-y-4">
          <FormField
            control={form.control}
            name="code"
            render={({ field }) => (
              <FormItem>
                <FormLabel required>{t("account.2fa.code_label")}</FormLabel>
                <FormControl>
                  <Input
                    inputMode="numeric"
                    autoComplete="one-time-code"
                    maxLength={6}
                    placeholder={t("account.2fa.code_ph")}
                    {...field}
                  />
                </FormControl>
                <FormMessage />
              </FormItem>
            )}
          />
          <div className="flex gap-2">
            <Button type="submit" loading={enable.isPending}>
              <Check className="size-4" />
              {t("account.2fa.confirm")}
            </Button>
            <Button type="button" variant="outline" onClick={onCancel}>
              <X className="size-4" />
              {t("common.cancel")}
            </Button>
          </div>
        </form>
      </Form>
    </div>
  );
}
